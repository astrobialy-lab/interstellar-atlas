#!/usr/bin/env python3
"""Build the standalone Android APK used by Meta Quest.

This script is self-contained and does not import unity_build_common.py.
It writes the APK to Builds/Android and deliberately does not copy the
project's external Data folder; Quest data is installed separately.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path
from typing import List, Optional, Union

# This matches the layout used by the other build scripts under Tools/Builds/.
# Change it if this script is stored somewhere else in your project.
PROJECT_ROOT: Optional[Path] = Path(__file__).resolve().parents[2]

# Set this to the exact Android / Meta Quest Build Profile if auto-detection
# finds more than one matching profile. Relative paths are project-root based.
PROFILE_PATH: Optional[Path] = None

# Set an explicit Unity executable path, or None for automatic Hub discovery.
UNITY_EXE_PATH: Optional[Path] = Path(
    r"C:\Program Files\Unity\Hub\Editor\6000.4.12f1\Editor\Unity.exe"
)

PROFILE_DIR = Path("Assets/Settings/Build Profiles")
EDITOR_HELPER = Path("Assets/Editor/AutomatedProfileBuilder.cs")
BUILD_DIR_NAME = "Builds"
OUTPUT_FOLDER_NAME = "Android"
MAX_BUILD_ATTEMPTS = 5
RETRY_DELAY_SECONDS = 10
RENAME_TIMEOUT_SECONDS = 60
RENAME_RETRY_DELAY_SECONDS = 2

CSHARP_HELPER = r'''// Auto-generated by build_android.py. Do not edit unless needed.
using System;
using UnityEditor;
using UnityEditor.Build.Profile;
using UnityEditor.Build.Reporting;
using UnityEngine;

public static class AutomatedProfileBuilder
{
    public static void Build()
    {
        try
        {
            string profilePath = Environment.GetEnvironmentVariable("UNITY_AUTOBUILD_PROFILE_PATH");
            string outputPath = Environment.GetEnvironmentVariable("UNITY_AUTOBUILD_OUTPUT_PATH");

            if (string.IsNullOrWhiteSpace(profilePath))
                throw new InvalidOperationException("Missing UNITY_AUTOBUILD_PROFILE_PATH environment variable.");
            if (string.IsNullOrWhiteSpace(outputPath))
                throw new InvalidOperationException("Missing UNITY_AUTOBUILD_OUTPUT_PATH environment variable.");

            profilePath = profilePath.Replace('\\', '/');
            BuildProfile profile = AssetDatabase.LoadAssetAtPath<BuildProfile>(profilePath);
            if (profile == null)
                throw new InvalidOperationException("Could not load Build Profile asset at: " + profilePath);

            outputPath = System.IO.Path.GetFullPath(outputPath);
            string parent = System.IO.Path.GetDirectoryName(outputPath);
            if (!string.IsNullOrEmpty(parent))
                System.IO.Directory.CreateDirectory(parent);

            Debug.Log("Automated build profile: " + profile.name);
            Debug.Log("Automated build output: " + outputPath);

            BuildPlayerWithProfileOptions options = new BuildPlayerWithProfileOptions
            {
                buildProfile = profile,
                locationPathName = outputPath,
                options = BuildOptions.None
            };

            BuildReport report = BuildPipeline.BuildPlayer(options);
            if (report != null && report.summary.result == BuildResult.Succeeded)
            {
                Debug.Log("AUTOMATED_BUILD_RESULT=SUCCEEDED; size=" + report.summary.totalSize + " bytes");
                EditorApplication.Exit(0);
            }
            else
            {
                string result = report == null ? "no BuildReport returned" : report.summary.result.ToString();
                Debug.LogError("AUTOMATED_BUILD_RESULT=FAILED; result=" + result);
                EditorApplication.Exit(1);
            }
        }
        catch (Exception ex)
        {
            Debug.LogException(ex);
            Debug.LogError("AUTOMATED_BUILD_RESULT=FAILED; exception");
            EditorApplication.Exit(1);
        }
    }
}
'''


def normalize_name(value: str) -> str:
    return re.sub(r"[^a-z0-9]", "", value.lower())


def find_unity_exe(override: Optional[Union[str, Path]]) -> Path:
    if override is not None:
        candidate = Path(override).expanduser()
        if candidate.is_file():
            return candidate.resolve()
        raise FileNotFoundError(f"Unity executable not found: {candidate}")

    candidates: List[Path] = []
    if sys.platform == "win32":
        hub_editors = Path(r"C:\Program Files\Unity\Hub\Editor")
        if hub_editors.is_dir():
            candidates = list(hub_editors.glob("*/Editor/Unity.exe"))
    elif sys.platform == "darwin":
        hub_editors = Path("/Applications/Unity/Hub/Editor")
        if hub_editors.is_dir():
            candidates = list(hub_editors.glob("*/Unity.app/Contents/MacOS/Unity"))
    else:
        hub_editors = Path.home() / "Unity" / "Hub" / "Editor"
        if hub_editors.is_dir():
            candidates = list(hub_editors.glob("*/Editor/Unity"))

    candidates = [path for path in candidates if path.is_file()]
    if candidates:
        candidates.sort(key=lambda path: path.parts[-5] if sys.platform == "darwin" else path.parts[-3], reverse=True)
        print(f"Using detected Unity Editor: {candidates[0]}")
        return candidates[0].resolve()

    raise FileNotFoundError(
        "Could not find a Unity Editor installation. Set UNITY_EXE_PATH near the top "
        "of build_android.py to the Unity executable."
    )


def discover_profiles(project: Path) -> List[Path]:
    root = project / PROFILE_DIR
    if not root.is_dir():
        return []
    return sorted(path for path in root.rglob("*.asset") if path.is_file())


def choose_android_profile(
    profile_assets: List[Path],
    override: Optional[Union[str, Path]],
    project: Path,
) -> Path:
    if override is not None and str(override).strip():
        relative_path = Path(str(override).replace("/", os.sep)).expanduser()
        profile = relative_path if relative_path.is_absolute() else project / relative_path
        if not profile.is_file():
            raise FileNotFoundError(f"Profile asset does not exist: {profile}")
        if profile.suffix.lower() != ".asset":
            raise ValueError(f"Profile must be a .asset file: {profile}")
        return profile.resolve()

    hints = ("android", "quest", "metaquest")
    matches = [
        path for path in profile_assets
        if any(hint in normalize_name(path.stem) for hint in hints)
    ]
    if not matches:
        available = "\n".join(
            f"  {path.relative_to(project).as_posix()}" for path in profile_assets
        ) or "  (no .asset files found in the default profile directory)"
        raise FileNotFoundError(
            "Could not automatically find an Android / Meta Quest Build Profile. "
            f"Available profile assets:\n{available}\n"
            "Set PROFILE_PATH near the top of build_android.py to the correct profile asset path."
        )

    # Prefer an explicitly named MetaQuest profile, then Quest, then Android.
    # This preserves Quest-specific settings when both Quest and Android profiles exist.
    for preferred_name in ("metaquest", "quest", "android"):
        exact = [path for path in matches if normalize_name(path.stem) == preferred_name]
        if len(exact) == 1:
            return exact[0].resolve()
        if len(exact) > 1:
            break

    if len(matches) == 1:
        return matches[0].resolve()

    choices = "\n".join(f"  {path.relative_to(project).as_posix()}" for path in matches)
    raise RuntimeError(
        "Multiple Android / Meta Quest Build Profiles match; refusing to guess:\n"
        f"{choices}\nSet PROFILE_PATH near the top of build_android.py to the correct profile asset path."
    )


def read_product_name(project: Path) -> str:
    settings = project / "ProjectSettings" / "ProjectSettings.asset"
    if settings.is_file():
        content = settings.read_text(encoding="utf-8", errors="replace")
        match = re.search(r"(?m)^\s*productName:\s*(.*?)\s*$", content)
        if match:
            name = match.group(1).strip().strip('"').strip("'")
            name = re.sub(r'[<>:"/\\|?*\x00-\x1f]', "_", name).strip().rstrip(".")
            if name:
                return name
    return "UnityPlayer"


def write_helper(project: Path) -> Path:
    helper_path = project / EDITOR_HELPER
    helper_path.parent.mkdir(parents=True, exist_ok=True)
    desired = CSHARP_HELPER.lstrip()
    existing = (
        helper_path.read_text(encoding="utf-8", errors="replace")
        if helper_path.exists() else None
    )
    if existing != desired:
        helper_path.write_text(desired, encoding="utf-8", newline="\n")
        print(f"Wrote Unity Editor build helper: {helper_path}")
    return helper_path


def remove_path(path: Path) -> None:
    if path.is_symlink() or path.is_file():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)

def rename_with_retry(source: Path, destination: Path) -> None:
    deadline = time.monotonic() + RENAME_TIMEOUT_SECONDS
    attempt = 0

    while True:
        attempt += 1

        try:
            source.rename(destination)
            return

        except OSError as exc:
            winerror = getattr(exc, "winerror", None)
            retryable = isinstance(exc, PermissionError) or winerror in (5, 32, 33)

            remaining = deadline - time.monotonic()
            if not retryable:
                raise

            if remaining <= 0:
                raise TimeoutError(
                    f"Could not rename '{source}' to '{destination}' "
                    f"within {RENAME_TIMEOUT_SECONDS} seconds. Last error: {exc}"
                ) from exc

            delay = min(RENAME_RETRY_DELAY_SECONDS, remaining)
            print(
                f"Rename failed (attempt {attempt}): {exc}. "
                f"Retrying in {delay:.1f} seconds..."
            )
            time.sleep(delay)


def replace_build_directory(staging_dir: Path, output_dir: Path, backup_dir: Path) -> None:
    moved_old_build = False

    if output_dir.exists() and backup_dir.exists():
        remove_path(backup_dir)

    if output_dir.exists():
        rename_with_retry(output_dir, backup_dir)
        moved_old_build = True
    elif backup_dir.exists():
        moved_old_build = True

    try:
        rename_with_retry(staging_dir, output_dir)

    except OSError:
        if moved_old_build and backup_dir.exists() and not output_dir.exists():
            try:
                rename_with_retry(backup_dir, output_dir)
                print("Restored the previous Android build after replacement failed.")
            except OSError as restore_error:
                print(f"WARNING: previous build remains at {backup_dir}: {restore_error}")
        raise

    if backup_dir.exists():
        try:
            remove_path(backup_dir)
        except OSError as exc:
            print(f"WARNING: new Android build installed, but backup could not be removed: {exc}")
            print(f"Old backup remains at: {backup_dir}")


def build_android() -> int:
    project = (
        Path(PROJECT_ROOT).expanduser().resolve()
        if PROJECT_ROOT is not None else Path(__file__).resolve().parent
    )
    if not (project / "Assets").is_dir() or not (project / "ProjectSettings").is_dir():
        print(f"ERROR: this doesn't look like a Unity project root: {project}")
        print("Update PROJECT_ROOT near the top of build_android.py.")
        return 2

    print(f"Project: {project}")
    try:
        profile = choose_android_profile(discover_profiles(project), PROFILE_PATH, project)
        unity_exe = find_unity_exe(UNITY_EXE_PATH)
    except (FileNotFoundError, RuntimeError, ValueError) as exc:
        print(f"ERROR: {exc}")
        return 2

    product_name = read_product_name(project)
    builds_root = project / BUILD_DIR_NAME
    output_dir = builds_root / OUTPUT_FOLDER_NAME
    staging_dir = builds_root / f".{OUTPUT_FOLDER_NAME}.staging"
    backup_dir = builds_root / f".{OUTPUT_FOLDER_NAME}.backup"
    staged_apk = staging_dir / f"{product_name}.apk"
    final_apk = output_dir / staged_apk.name

    log_dir = builds_root / "_logs"
    log_dir.mkdir(parents=True, exist_ok=True)
    log_path = log_dir / "build_android.log"
    log_path.unlink(missing_ok=True)

    try:
        builds_root.mkdir(parents=True, exist_ok=True)
        if not output_dir.exists() and backup_dir.exists():
            rename_with_retry(backup_dir, output_dir)
            print(f"Recovered previous Android build from backup: {output_dir}")
        remove_path(staging_dir)
    except OSError as exc:
        print(f"ERROR: could not prepare staging/backup directories: {exc}")
        return 2

    try:
        write_helper(project)
    except OSError as exc:
        print(f"ERROR: could not write Unity Editor build helper: {exc}")
        return 2

    profile_relative = profile.relative_to(project).as_posix()
    env = os.environ.copy()
    env["UNITY_AUTOBUILD_PROFILE_PATH"] = profile_relative
    env["UNITY_AUTOBUILD_OUTPUT_PATH"] = str(staged_apk.resolve())

    command = [
        str(unity_exe),
        "-batchmode",
        "-quit",
        "-projectPath", str(project),
        "-activeBuildProfile", profile_relative,
        "-executeMethod", "AutomatedProfileBuilder.Build",
        "-logFile", str(log_path.resolve()),
    ]

    print("\n" + "=" * 72)
    print("Building ANDROID (Meta Quest)")
    print(f"Unity:          {unity_exe}")
    print(f"Profile:        {profile_relative}")
    print(f"Final output:   {final_apk}")
    print(f"Staging folder: {staging_dir}")
    print(f"Log:            {log_path}")
    print("External Data is not copied; install Quest data separately.")
    print("The existing build will be kept unless the new build succeeds.")
    print("=" * 72)

    scene_setup_path = project / "Library" / "LastSceneManagerSetup.txt"
    scene_setup_existed = scene_setup_path.is_file()
    scene_setup_backup = scene_setup_path.read_bytes() if scene_setup_existed else None

    result: Optional[subprocess.CompletedProcess] = None
    log_text = ""
    launch_error: Optional[str] = None

    try:
        for attempt in range(1, MAX_BUILD_ATTEMPTS + 1):
            try:
                remove_path(staging_dir)
                staging_dir.mkdir(parents=True, exist_ok=True)
            except OSError as exc:
                launch_error = f"could not prepare staging directory: {exc}"
                print(f"ERROR: {launch_error}")
                break

            attempt_log_path = log_dir / f"build_android_attempt{attempt}.log"
            attempt_log_path.unlink(missing_ok=True)
            attempt_command = command.copy()
            attempt_command[attempt_command.index("-logFile") + 1] = str(attempt_log_path.resolve())

            print(f"\nBuild attempt {attempt}/{MAX_BUILD_ATTEMPTS}")
            try:
                result = subprocess.run(attempt_command, cwd=project, env=env, check=False)
            except OSError as exc:
                launch_error = f"could not launch Unity: {exc}"
                print(f"ERROR: {launch_error}")
                break

            log_text = (
                attempt_log_path.read_text(encoding="utf-8", errors="replace")
                if attempt_log_path.exists() else ""
            )
            if attempt_log_path.is_file():
                try:
                    shutil.copy2(attempt_log_path, log_path)
                except OSError as exc:
                    print(f"WARNING: could not update summary log: {exc}")

            reported_success = "AUTOMATED_BUILD_RESULT=SUCCEEDED" in log_text
            reported_failure = "AUTOMATED_BUILD_RESULT=FAILED" in log_text
            if result.returncode == 0 and reported_success:
                break

            compilation_error = bool(re.search(
                r"\berror CS\d{4}\b|Scripts have compiler errors|Compilation failed",
                log_text,
                re.IGNORECASE,
            ))
            lower_log = log_text.lower()
            crash_detected = any(marker in lower_log for marker in (
                "getmanagerfromcontext:",
                "fatal error!",
                "crash!!!",
                "editor has crashed",
            ))
            should_retry = (
                attempt < MAX_BUILD_ATTEMPTS
                and not reported_success
                and not reported_failure
                and not compilation_error
                and (result.returncode != 0 or crash_detected)
            )
            if not should_retry:
                break

            print(f"Unity exited unexpectedly (exit code {result.returncode}).")
            print(f"Retrying in {RETRY_DELAY_SECONDS} seconds...")
            time.sleep(RETRY_DELAY_SECONDS)

    finally:
        try:
            if scene_setup_existed and scene_setup_backup is not None:
                scene_setup_path.parent.mkdir(parents=True, exist_ok=True)
                scene_setup_path.write_bytes(scene_setup_backup)
            elif not scene_setup_existed and scene_setup_path.exists():
                scene_setup_path.unlink()
        except OSError as exc:
            print(f"WARNING: could not restore Editor scene state: {exc}")

    success = (
        launch_error is None
        and result is not None
        and result.returncode == 0
        and "AUTOMATED_BUILD_RESULT=SUCCEEDED" in log_text
    )
    if not success:
        try:
            remove_path(staging_dir)
        except OSError as exc:
            print(f"WARNING: could not remove failed staging folder: {exc}")
            print(f"Partial build remains at: {staging_dir}")

        if launch_error:
            print(f"FAILED: Android build. {launch_error}")
        else:
            exit_code = result.returncode if result is not None else "unknown"
            print(f"FAILED: Android build. Unity exit code: {exit_code}")
        print(f"Inspect the log: {log_path}")
        print(f"Per-attempt logs: {log_dir / 'build_android_attempt*.log'}")
        if (
            "AUTOMATED_BUILD_RESULT=FAILED" not in log_text
            and "AUTOMATED_BUILD_RESULT=SUCCEEDED" not in log_text
        ):
            print("Unity did not report a build result. Check for a startup crash, C# errors, or another Unity instance using this project.")
        return 1

    try:
        replace_build_directory(staging_dir, output_dir, backup_dir)
    except (OSError, shutil.Error) as exc:
        print(f"ERROR: Android build succeeded, but installing it failed: {exc}")
        print("The previous build has been preserved where possible.")
        try:
            remove_path(staging_dir)
        except OSError:
            pass
        return 1

    print("SUCCESS: Android (Meta Quest) build completed.")
    print(f"Installed APK: {final_apk}")
    return 0


if __name__ == "__main__":
    raise SystemExit(build_android())
