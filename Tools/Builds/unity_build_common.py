#!/usr/bin/env python3
"""Shared implementation used by the per-platform Unity build scripts.

Keep this file beside build_windows.py, build_linux.py, build_macos.py,
build_meta_quest.py, and build_all.py, in the Unity project root.

Builds are produced in a staging directory. Only after Unity succeeds (and
external Data has been copied, where applicable) is the staging directory
swapped into the final platform directory. The previous successful build is
kept intact if the new build fails.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
import time
from pathlib import Path
from typing import List, Optional, Union

# Update this once if your Unity installation is in a different location.
# Set to None to let the script search the standard Unity Hub installation path.
DEFAULT_UNITY_EXE_PATH: Optional[Path] = Path(
    r"C:\Program Files\Unity\Hub\Editor\6000.4.12f1\Editor\Unity.exe"
)

PROFILE_DIR = Path("Assets/Settings/Build Profiles")
EDITOR_HELPER = Path("Assets/Editor/AutomatedProfileBuilder.cs")
BUILD_DIR_NAME = "Builds"
DATA_DIR_NAME = "Data"
MAX_BUILD_ATTEMPTS = 3
RETRY_DELAY_SECONDS = 5

PROFILE_HINTS = {
    "windows": ("windows",),
    "linux": ("linux",),
    "macos": ("macos", "mac", "osx"),
    "quest": ("quest",),
}

CSHARP_HELPER = r'''// Auto-generated by unity_build_common.py. Do not edit unless needed.
using System;
using UnityEditor;
using UnityEditor.Build.Profile;
using UnityEditor.Build.Reporting;
using UnityEngine;

public static class AutomatedProfileBuilder
{
    public static void Build()
    {
        try
        {
            string profilePath = Environment.GetEnvironmentVariable("UNITY_AUTOBUILD_PROFILE_PATH");
            string outputPath = Environment.GetEnvironmentVariable("UNITY_AUTOBUILD_OUTPUT_PATH");

            if (string.IsNullOrWhiteSpace(profilePath))
                throw new InvalidOperationException("Missing UNITY_AUTOBUILD_PROFILE_PATH environment variable.");
            if (string.IsNullOrWhiteSpace(outputPath))
                throw new InvalidOperationException("Missing UNITY_AUTOBUILD_OUTPUT_PATH environment variable.");

            profilePath = profilePath.Replace('\\', '/');
            BuildProfile profile = AssetDatabase.LoadAssetAtPath<BuildProfile>(profilePath);
            if (profile == null)
                throw new InvalidOperationException("Could not load Build Profile asset at: " + profilePath);

            outputPath = System.IO.Path.GetFullPath(outputPath);
            string parent = System.IO.Path.GetDirectoryName(outputPath);
            if (!string.IsNullOrEmpty(parent))
                System.IO.Directory.CreateDirectory(parent);

            Debug.Log("Automated build profile: " + profile.name);
            Debug.Log("Automated build output: " + outputPath);

            BuildPlayerWithProfileOptions options = new BuildPlayerWithProfileOptions
            {
                buildProfile = profile,
                locationPathName = outputPath,
                options = BuildOptions.None
            };

            BuildReport report = BuildPipeline.BuildPlayer(options);
            if (report != null && report.summary.result == BuildResult.Succeeded)
            {
                Debug.Log("AUTOMATED_BUILD_RESULT=SUCCEEDED; size=" + report.summary.totalSize + " bytes");
                EditorApplication.Exit(0);
            }
            else
            {
                string result = report == null ? "no BuildReport returned" : report.summary.result.ToString();
                Debug.LogError("AUTOMATED_BUILD_RESULT=FAILED; result=" + result);
                EditorApplication.Exit(1);
            }
        }
        catch (Exception ex)
        {
            Debug.LogException(ex);
            Debug.LogError("AUTOMATED_BUILD_RESULT=FAILED; exception");
            EditorApplication.Exit(1);
        }
    }
}
'''


def normalize_name(value: str) -> str:
    return re.sub(r"[^a-z0-9]", "", value.lower())


def find_unity_exe(override: Optional[Union[str, Path]]) -> Path:
    candidate_value = override if override is not None else DEFAULT_UNITY_EXE_PATH
    if candidate_value is not None:
        candidate = Path(candidate_value).expanduser()
        if candidate.is_file():
            return candidate.resolve()
        raise FileNotFoundError(
            f"Unity executable not found: {candidate}\n"
            "Update DEFAULT_UNITY_EXE_PATH in unity_build_common.py, or set it to None "
            "to search standard Unity Hub installations."
        )

    hub_editors = Path(r"C:\Program Files\Unity\Hub\Editor")
    if hub_editors.is_dir():
        candidates = sorted(
            hub_editors.glob("*/Editor/Unity.exe"),
            key=lambda p: p.parts[-3],
            reverse=True,
        )
        if candidates:
            print(f"Using detected Unity Editor: {candidates[0]}")
            return candidates[0].resolve()

    raise FileNotFoundError(
        "Could not find Unity.exe. Set DEFAULT_UNITY_EXE_PATH in unity_build_common.py "
        "to your Unity installation, or set it to None to try automatic discovery."
    )


def discover_profile_assets(project: Path) -> List[Path]:
    root = project / PROFILE_DIR
    if not root.is_dir():
        return []
    return sorted(p for p in root.rglob("*.asset") if p.is_file())


def choose_profile(
    target: str,
    profile_assets: List[Path],
    override: Optional[Union[str, Path]],
    project: Path,
) -> Path:
    if override is not None and str(override).strip():
        rel = Path(str(override).replace("/", os.sep)).expanduser()
        profile = rel if rel.is_absolute() else project / rel
        if not profile.is_file():
            raise FileNotFoundError(f"Profile asset does not exist: {profile}")
        if profile.suffix.lower() != ".asset":
            raise ValueError(f"Profile must be a .asset file: {profile}")
        return profile.resolve()

    hints = PROFILE_HINTS[target]
    matches = [p for p in profile_assets if any(hint in normalize_name(p.stem) for hint in hints)]

    if target == "quest" and not matches:
        # Some projects name the standalone Quest profile simply "Android".
        matches = [p for p in profile_assets if "android" in normalize_name(p.stem)]

    if not matches:
        available = "\n".join(f"  {p.relative_to(project).as_posix()}" for p in profile_assets)
        if not available:
            available = "  (no .asset files found in the default profile directory)"
        raise FileNotFoundError(
            f"Could not automatically find the {target} Build Profile. Available profile assets:\n"
            f"{available}\nSet PROFILE_PATH near the top of build_{'meta_quest' if target == 'quest' else target}.py "
            "to the correct profile asset path."
        )

    exact_names = {
        "windows": {"windows"},
        "linux": {"linux"},
        "macos": {"macos", "osx"},
        "quest": {"quest", "metaquest", "android"},
    }
    exact = [p for p in matches if normalize_name(p.stem) in exact_names[target]]
    if len(exact) == 1:
        return exact[0].resolve()
    if len(matches) == 1:
        return matches[0].resolve()

    choices = "\n".join(f"  {p.relative_to(project).as_posix()}" for p in matches)
    script_name = "meta_quest" if target == "quest" else target
    raise RuntimeError(
        f"Multiple Build Profiles match '{target}'; refusing to guess:\n{choices}\n"
        f"Set PROFILE_PATH near the top of build_{script_name}.py to the correct profile asset path."
    )


def read_product_name(project: Path) -> str:
    settings = project / "ProjectSettings" / "ProjectSettings.asset"
    if settings.is_file():
        content = settings.read_text(encoding="utf-8", errors="replace")
        match = re.search(r"(?m)^\s*productName:\s*(.*?)\s*$", content)
        if match:
            name = match.group(1).strip().strip('"').strip("'")
            name = re.sub(r'[<>:"/\\|?*\x00-\x1f]', "_", name).strip().rstrip(".")
            if name:
                return name
    return "UnityPlayer"


def write_helper(project: Path) -> Path:
    helper_path = project / EDITOR_HELPER
    helper_path.parent.mkdir(parents=True, exist_ok=True)
    desired = CSHARP_HELPER.lstrip()
    existing = helper_path.read_text(encoding="utf-8", errors="replace") if helper_path.exists() else None
    if existing != desired:
        helper_path.write_text(desired, encoding="utf-8", newline="\n")
        print(f"Wrote Unity Editor build helper: {helper_path}")
    return helper_path


def remove_path(path: Path) -> None:
    """Remove a file, symlink, or directory if it exists."""
    if path.is_symlink() or path.is_file():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)


def copy_external_data(source: Path, destination: Path) -> bool:
    if not source.is_dir():
        print(f"WARNING: external Data folder not found; skipped: {source}")
        return False
    print(f"Copying external data:\n  from: {source}\n  to:   {destination}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(
        source,
        destination,
        dirs_exist_ok=True,
        ignore=shutil.ignore_patterns(".DS_Store", "Thumbs.db"),
    )
    return True


def replace_build_directory(staging_dir: Path, output_dir: Path, backup_dir: Path) -> None:
    """Install a completed staged build, rolling back if the swap fails."""
    moved_old_build = False

    # If both exist, output_dir is the current build and any backup is stale.
    # If output_dir is missing, preserve backup_dir as a recovery copy.
    if output_dir.exists() and backup_dir.exists():
        remove_path(backup_dir)

    if output_dir.exists():
        output_dir.rename(backup_dir)
        moved_old_build = True
    elif backup_dir.exists():
        # Recovery from a previous interrupted swap: the backup is the only
        # remaining copy of the previous build, so keep it until commit works.
        moved_old_build = True

    try:
        staging_dir.rename(output_dir)
    except OSError:
        if moved_old_build and backup_dir.exists() and not output_dir.exists():
            try:
                backup_dir.rename(output_dir)
                print("Restored the previous build after the replacement failed.")
            except OSError as restore_error:
                print(
                    "WARNING: could not automatically restore the previous build. "
                    f"It may still be at: {backup_dir}\nDetails: {restore_error}"
                )
        raise

    # The new build is now installed. Removing the backup is cleanup only;
    # a cleanup error must not mark the successful replacement as failed.
    if backup_dir.exists():
        try:
            remove_path(backup_dir)
        except OSError as exc:
            print(f"WARNING: new build installed, but old backup could not be removed: {exc}")
            print(f"Old backup remains at: {backup_dir}")


def build_target(
    target: str,
    *,
    script_file: str,
    project_root: Optional[Union[str, Path]] = None,
    unity_exe_path: Optional[Union[str, Path]] = None,
    profile_path: Optional[Union[str, Path]] = None,
    copy_data_to_build: bool = True,
) -> int:
    """Build one profile and return an exit code suitable for a command line."""
    if target not in ("windows", "linux", "macos", "quest"):
        print(f"ERROR: unsupported target: {target}")
        return 2

    project = Path(project_root).expanduser().resolve() if project_root else Path(script_file).resolve().parent
    if not (project / "Assets").is_dir() or not (project / "ProjectSettings").is_dir():
        print(f"ERROR: this doesn't look like a Unity project root: {project}")
        print("Place these scripts beside Assets/ and ProjectSettings/, or set PROJECT_ROOT in the build script.")
        return 2

    print(f"Project: {project}")
    profile_assets = discover_profile_assets(project)
    try:
        profile = choose_profile(target, profile_assets, profile_path, project)
        unity_exe = find_unity_exe(unity_exe_path)
    except (FileNotFoundError, RuntimeError, ValueError) as exc:
        print(f"ERROR: {exc}")
        return 2

    product_name = read_product_name(project)
    output_folder = {"windows": "Windows", "linux": "Linux", "macos": "macOS", "quest": "Android"}[target]
    builds_root = project / BUILD_DIR_NAME
    output_dir = builds_root / output_folder
    staging_dir = builds_root / f".{output_folder}.staging"
    backup_dir = builds_root / f".{output_folder}.backup"

    # Build paths inside staging_dir. The whole staging directory will become
    # output_dir only after the player and any external Data have completed.
    staged_output_path = {
        "windows": staging_dir / f"{product_name}.exe",
        "linux": staging_dir / f"{product_name}.x86_64",
        "macos": staging_dir / f"{product_name}.app",
        "quest": staging_dir / f"{product_name}.apk",
    }[target]
    final_output_path = output_dir / staged_output_path.name

    log_dir = builds_root / "_logs"
    log_dir.mkdir(parents=True, exist_ok=True)
    log_path = log_dir / f"build_{target}.log"
    log_path.unlink(missing_ok=True)

    # Recover the old build if an earlier process was interrupted between its
    # two directory renames. Do not remove the active output directory here.
    try:
        builds_root.mkdir(parents=True, exist_ok=True)
        if not output_dir.exists() and backup_dir.exists():
            backup_dir.rename(output_dir)
            print(f"Recovered previous build from backup: {output_dir}")
        remove_path(staging_dir)
    except OSError as exc:
        print(f"ERROR: could not prepare staging/backup directories: {exc}")
        return 2

    try:
        write_helper(project)
    except OSError as exc:
        print(f"ERROR: could not write Unity Editor build helper: {exc}")
        return 2

    profile_relative = profile.relative_to(project).as_posix()
    env = os.environ.copy()
    env["UNITY_AUTOBUILD_PROFILE_PATH"] = profile_relative
    env["UNITY_AUTOBUILD_OUTPUT_PATH"] = str(staged_output_path.resolve())

    command = [
        str(unity_exe),
        "-batchmode",
        "-quit",
        "-projectPath", str(project),
        "-activeBuildProfile", profile_relative,
        "-executeMethod", "AutomatedProfileBuilder.Build",
        "-logFile", str(log_path.resolve()),
    ]

    print("\n" + "=" * 72)
    print(f"Building {target.upper()}")
    print(f"Unity:          {unity_exe}")
    print(f"Profile:        {profile_relative}")
    print(f"Final output:   {final_output_path}")
    print(f"Staging folder: {staging_dir}")
    print(f"Log:            {log_path}")
    print("The existing build will be kept unless the new build succeeds.")
    print("=" * 72)

    # Preserve the Editor's last-open scene setup across batch builds.
    scene_setup_path = project / "Library" / "LastSceneManagerSetup.txt"
    scene_setup_existed = scene_setup_path.is_file()
    scene_setup_backup = scene_setup_path.read_bytes() if scene_setup_existed else None

    result: Optional[subprocess.CompletedProcess] = None
    log_text = ""
    launch_error: Optional[str] = None

    try:
        for attempt in range(1, MAX_BUILD_ATTEMPTS + 1):
            # Each retry gets a clean staging directory, so partial output from
            # a crashed/failed attempt cannot contaminate the next attempt.
            try:
                remove_path(staging_dir)
                staging_dir.mkdir(parents=True, exist_ok=True)
            except OSError as exc:
                launch_error = f"could not prepare staging directory: {exc}"
                print(f"ERROR: {launch_error}")
                break

            attempt_log_path = log_dir / f"build_{target}_attempt{attempt}.log"
            attempt_log_path.unlink(missing_ok=True)

            attempt_command = command.copy()
            log_index = attempt_command.index("-logFile") + 1
            attempt_command[log_index] = str(attempt_log_path.resolve())

            print(f"\nBuild attempt {attempt}/{MAX_BUILD_ATTEMPTS}")

            try:
                result = subprocess.run(
                    attempt_command,
                    cwd=project,
                    env=env,
                    check=False,
                )
            except OSError as exc:
                launch_error = f"could not launch Unity: {exc}"
                print(f"ERROR: {launch_error}")
                break

            log_text = (
                attempt_log_path.read_text(encoding="utf-8", errors="replace")
                if attempt_log_path.exists()
                else ""
            )

            # Keep the stable log filename pointing to the latest attempt.
            if attempt_log_path.is_file():
                try:
                    shutil.copy2(attempt_log_path, log_path)
                except OSError as exc:
                    print(f"WARNING: could not update summary log: {exc}")

            reported_success = "AUTOMATED_BUILD_RESULT=SUCCEEDED" in log_text
            reported_failure = "AUTOMATED_BUILD_RESULT=FAILED" in log_text

            if result.returncode == 0 and reported_success:
                break

            # Avoid retrying normal C# compilation errors or an explicit build
            # failure. Only retry an unexpected exit with no reported result.
            compilation_error = bool(
                re.search(
                    r"\berror CS\d{4}\b|Scripts have compiler errors|Compilation failed",
                    log_text,
                    re.IGNORECASE,
                )
            )
            log_lower = log_text.lower()
            crash_detected = any(
                marker in log_lower
                for marker in (
                    "getmanagerfromcontext:",
                    "fatal error!",
                    "crash!!!",
                    "editor has crashed",
                )
            )
            should_retry = (
                attempt < MAX_BUILD_ATTEMPTS
                and not reported_success
                and not reported_failure
                and not compilation_error
                and (result.returncode != 0 or crash_detected)
            )

            if not should_retry:
                break

            print(f"Unity exited unexpectedly (exit code {result.returncode}).")
            print(f"Retrying in {RETRY_DELAY_SECONDS} seconds...")
            time.sleep(RETRY_DELAY_SECONDS)

    finally:
        # Restore the last-open scene setup even if Unity crashes.
        try:
            if scene_setup_existed and scene_setup_backup is not None:
                scene_setup_path.parent.mkdir(parents=True, exist_ok=True)
                scene_setup_path.write_bytes(scene_setup_backup)
            elif not scene_setup_existed and scene_setup_path.exists():
                scene_setup_path.unlink()
        except OSError as exc:
            print(f"WARNING: could not restore Editor scene state: {exc}")

    success = (
        launch_error is None
        and result is not None
        and result.returncode == 0
        and "AUTOMATED_BUILD_RESULT=SUCCEEDED" in log_text
    )

    if not success:
        # Remove incomplete output but leave the last successful build alone.
        try:
            remove_path(staging_dir)
        except OSError as exc:
            print(f"WARNING: could not remove failed staging folder: {exc}")
            print(f"Partial build remains at: {staging_dir}")

        if launch_error:
            print(f"FAILED: {target}. {launch_error}")
        else:
            exit_code = result.returncode if result is not None else "unknown"
            print(f"FAILED: {target}. Unity exit code: {exit_code}")
        print(f"Inspect the log: {log_path}")
        print(f"Per-attempt logs: {log_dir / f'build_{target}_attempt*.log'}")

        if (
            "AUTOMATED_BUILD_RESULT=FAILED" not in log_text
            and "AUTOMATED_BUILD_RESULT=SUCCEEDED" not in log_text
        ):
            print(
                "Unity did not report a build result. Check the logs for a startup crash, "
                "C# errors, or another Unity instance using this project."
            )
        return 1

    # Complete all post-build work in the staging folder before replacing the
    # existing build. If copying Data fails, the existing build is untouched.
    try:
        if copy_data_to_build and target in ("windows", "linux", "macos"):
            copy_external_data(project / DATA_DIR_NAME, staging_dir / DATA_DIR_NAME)

        replace_build_directory(staging_dir, output_dir, backup_dir)
    except (OSError, shutil.Error) as exc:
        print(f"ERROR: new build succeeded, but installation failed: {exc}")
        print("The previous build has been preserved where possible.")
        try:
            remove_path(staging_dir)
        except OSError:
            pass
        return 1

    print(f"SUCCESS: {target} build completed.")
    print(f"Installed build: {output_dir}")
    return 0
