using System;
using System.Collections;
using System.IO;
using System.Text;
using System.Threading;
using System.Threading.Tasks;
using Unity.SharpZipLib.Tar;
using UnityEngine;
using UnityEngine.SceneManagement;

/// <summary>
/// Runs in the first scene. On Quest, it extracts Meta Required Asset Files
/// from the application's OBB directory into persistentDataPath/Data, then
/// loads the main simulation scene. Desktop/editor builds simply load the
/// main scene and continue using their existing Data locations.
///
/// Expected manifest: Data_QuestTransfer_manifest.json, format_version 3,
/// generated by the current size-based Python TAR builder.
/// </summary>
public sealed class DataInstaller : MonoBehaviour
{
    [Header("Startup")]
    [SerializeField] private string mainSceneName = "Main";

    [Header("Installation")]
    [SerializeField] private bool deleteArchivesAfterExtraction = true;

    private bool ShouldDeleteArchivesAfterExtraction => deleteArchivesAfterExtraction;

    private const string ManifestName = "Data_AndroidTransfer_manifest.json";
    private const string ArchivePrefix = "Data_AndroidTransfer_";
    private const int SupportedManifestVersion = 3;

    private const string StageDirectoryName = ".DataInstalling";
    private const string BackupDirectoryName = ".DataPrevious";
    private const string CompletionMarkerName = ".DataInstallComplete";

    private int totalParts;
    private static int currentArchiveIndex;

    [Serializable]
    private sealed class TransferManifest
    {
        public int format_version;
        public string archive_format;
        public int part_count;
        public string transfer_id;
        public int file_count;
        public Part[] parts;
    }

    [Serializable]
    private sealed class Part
    {
        public string name;
        public long size_bytes;
        public int file_count;
        public string first_file;
    }

    private IEnumerator Start()
    {
#if UNITY_ANDROID && !UNITY_EDITOR
        string obbDirectory;
        try
        {
            obbDirectory = GetApplicationObbDirectory();
        }
        catch (Exception exception)
        {
            Fail("Could not locate the application's OBB directory.\n" + exception);
            yield break;
        }

        string manifestPath = Path.Combine(obbDirectory, ManifestName);
        if (!File.Exists(manifestPath))
        {
            Fail(
                "Required Asset Files were not found. Expected the manifest at:\n" + manifestPath +
                "\nCheck that the manifest and every TAR are marked required in Meta's asset configuration."
            );
            yield break;
        }

        TransferManifest manifest;
        try
        {
            manifest = ReadAndValidateManifest(manifestPath);
        }
        catch (Exception exception)
        {
            Fail("The data manifest is invalid.\n" + exception);
            yield break;
        }

        string persistentRoot = Application.persistentDataPath;
        string dataDirectory = Path.Combine(persistentRoot, "Data");
        string completionMarker = Path.Combine(persistentRoot, CompletionMarkerName);

        if (IsAlreadyInstalled(dataDirectory, completionMarker, manifest))
        {
            Debug.Log("[DataInstaller] Dataset is already installed: " + manifest.transfer_id);
            if (ShouldDeleteArchivesAfterExtraction)
                DeleteDownloadedArchives(obbDirectory, manifest);

            LoadMainScene();
            yield break;
        }

        Debug.Log(
            $"[DataInstaller] Installing {manifest.file_count:N0} files " +
            $"from {manifest.part_count} TAR archive(s)."
        );

        Interlocked.Exchange(ref currentArchiveIndex, 0);
        totalParts = manifest.part_count;

        Task installTask = Task.Run(() =>
            InstallData(
                obbDirectory,
                persistentRoot,
                completionMarker,
                manifest,
                ShouldDeleteArchivesAfterExtraction
            )
        );

        int lastReportedPart = -1;
        while (!installTask.IsCompleted)
        {
            int part = Interlocked.CompareExchange(ref currentArchiveIndex, 0, 0);
            if (part != lastReportedPart)
            {
                lastReportedPart = part;
                if (part > 0)
                    Debug.Log($"[DataInstaller] Extracting archive {part}/{totalParts}...");
            }
            yield return null;
        }

        if (installTask.IsFaulted)
        {
            Exception error = installTask.Exception?.GetBaseException();
            Fail("Data installation failed. Existing installed data has been preserved where possible.\n" + error);
            yield break;
        }

        Debug.Log("[DataInstaller] Data installation completed.");
        if (ShouldDeleteArchivesAfterExtraction)
            DeleteDownloadedArchives(obbDirectory, manifest);
        LoadMainScene();
#else
        // Editor and desktop builds already use their regular Data locations.
        LoadMainScene();
        yield break;
#endif
    }

#if UNITY_ANDROID && !UNITY_EDITOR
    private static string GetApplicationObbDirectory()
    {
        using (AndroidJavaClass unityPlayer = new AndroidJavaClass("com.unity3d.player.UnityPlayer"))
        using (AndroidJavaObject activity = unityPlayer.GetStatic<AndroidJavaObject>("currentActivity"))
        using (AndroidJavaObject obbDirectory = activity.Call<AndroidJavaObject>("getObbDir"))
        {
            if (obbDirectory == null)
                throw new IOException("Android Context.getObbDir() returned null.");

            string path = obbDirectory.Call<string>("getAbsolutePath");
            if (string.IsNullOrEmpty(path))
                throw new IOException("Android Context.getObbDir() returned an empty path.");

            return path;
        }
    }
#endif

    private static TransferManifest ReadAndValidateManifest(string manifestPath)
    {
        string json = File.ReadAllText(manifestPath, Encoding.UTF8);
        TransferManifest manifest = JsonUtility.FromJson<TransferManifest>(json);

        if (manifest == null)
            throw new InvalidDataException("Could not parse the JSON manifest.");
        if (manifest.format_version != SupportedManifestVersion)
            throw new InvalidDataException(
                $"Unsupported manifest version {manifest.format_version}; expected {SupportedManifestVersion}."
            );
        if (!string.Equals(manifest.archive_format, "uncompressed-tar", StringComparison.Ordinal))
            throw new InvalidDataException("Manifest does not describe uncompressed TAR archives.");
        if (string.IsNullOrEmpty(manifest.transfer_id))
            throw new InvalidDataException("Manifest has no transfer_id.");
        if (manifest.part_count < 1 || manifest.parts == null || manifest.parts.Length != manifest.part_count)
            throw new InvalidDataException("Manifest part_count does not match its parts array.");
        if (manifest.file_count < 1)
            throw new InvalidDataException("Manifest file_count must be greater than zero.");

        int totalFiles = 0;
        for (int index = 0; index < manifest.parts.Length; index++)
        {
            Part part = manifest.parts[index];
            string expectedName = $"{ArchivePrefix}{index + 1:0000}.tar";

            if (part == null || !string.Equals(part.name, expectedName, StringComparison.Ordinal))
                throw new InvalidDataException($"Unexpected TAR name/order at part {index + 1}.");
            if (part.size_bytes <= 0 || part.file_count < 1)
                throw new InvalidDataException($"Invalid size or file count for {part.name}.");
            if (Path.GetFileName(part.name) != part.name)
                throw new InvalidDataException($"Invalid archive filename: {part.name}");

            totalFiles += part.file_count;
        }

        if (totalFiles != manifest.file_count)
            throw new InvalidDataException(
                $"Manifest file count mismatch: parts contain {totalFiles}, manifest says {manifest.file_count}."
            );

        return manifest;
    }

    private static bool IsAlreadyInstalled(
        string dataDirectory,
        string completionMarker,
        TransferManifest manifest)
    {
        if (!Directory.Exists(dataDirectory) || !File.Exists(completionMarker))
            return false;

        string marker = File.ReadAllText(completionMarker, Encoding.UTF8).Trim();
        string expected = manifest.transfer_id + "|" + manifest.file_count;
        return string.Equals(marker, expected, StringComparison.Ordinal);
    }

    private static void InstallData(
        string obbDirectory,
        string persistentRoot,
        string completionMarker,
        TransferManifest manifest,
        bool deleteArchivesAfterExtraction)
    {
        string stageRoot = Path.Combine(persistentRoot, StageDirectoryName);
        string stageData = Path.Combine(stageRoot, "Data");
        string finalData = Path.Combine(persistentRoot, "Data");
        string backupData = Path.Combine(persistentRoot, BackupDirectoryName);
        string stageTransferMarker = Path.Combine(stageRoot, ".transfer_id");

        Directory.CreateDirectory(persistentRoot);

        // Recover a previous interrupted promotion before starting another install.
        if (!Directory.Exists(finalData) && Directory.Exists(backupData))
            Directory.Move(backupData, finalData);

        if (Directory.Exists(stageRoot))
        {
            string previousTransferId = File.Exists(stageTransferMarker)
                ? File.ReadAllText(stageTransferMarker, Encoding.UTF8).Trim()
                : string.Empty;

            if (!string.Equals(previousTransferId, manifest.transfer_id, StringComparison.Ordinal))
                Directory.Delete(stageRoot, true);
        }

        Directory.CreateDirectory(stageRoot);
        File.WriteAllText(stageTransferMarker, manifest.transfer_id, Encoding.UTF8);

        for (int index = 0; index < manifest.parts.Length; index++)
        {
            Part part = manifest.parts[index];
            Interlocked.Exchange(ref currentArchiveIndex, index + 1);

            string archivePath = Path.Combine(obbDirectory, part.name);
            string partMarker = Path.Combine(stageRoot, "." + part.name + ".done");
            string expectedPartMarker =
                manifest.transfer_id + "|" + part.name + "|" + part.size_bytes + "|" + part.file_count;

            bool partAlreadyExtracted =
                File.Exists(partMarker) &&
                string.Equals(
                    File.ReadAllText(partMarker, Encoding.UTF8).Trim(),
                    expectedPartMarker,
                    StringComparison.Ordinal
                ) &&
                SampleFileExists(stageData, part.first_file);

            if (partAlreadyExtracted)
            {
                if (deleteArchivesAfterExtraction && File.Exists(archivePath))
                    TryDelete(archivePath, false);
                continue;
            }

            if (!File.Exists(archivePath))
            {
                throw new FileNotFoundException(
                    $"Required asset archive is missing: {archivePath}. " +
                    "Check that this TAR is marked required in Meta's asset configuration.",
                    archivePath
                );
            }

            long actualSize = new FileInfo(archivePath).Length;
            if (actualSize != part.size_bytes)
            {
                throw new InvalidDataException(
                    $"Archive size mismatch for {part.name}: expected {part.size_bytes}, found {actualSize}."
                );
            }

            int extractedFileCount = ExtractTarArchive(archivePath, stageRoot);
            if (extractedFileCount != part.file_count)
            {
                throw new InvalidDataException(
                    $"File count mismatch in {part.name}: expected {part.file_count}, extracted {extractedFileCount}."
                );
            }

            if (!SampleFileExists(stageData, part.first_file))
            {
                throw new InvalidDataException(
                    $"The sample file from {part.name} was not found after extraction: {part.first_file}"
                );
            }

            // Write the part marker only after the entire archive has extracted and passed checks.
            WriteTextAtomic(partMarker, expectedPartMarker);

            // Required Asset Files are copies in the OBB directory. Keep each archive only
            // until its extracted contents have been verified.
            if (deleteArchivesAfterExtraction)
                TryDelete(archivePath, false);
        }

        if (!Directory.Exists(stageData))
            throw new DirectoryNotFoundException("TAR extraction completed without creating the Data directory.");

        foreach (Part part in manifest.parts)
        {
            if (!SampleFileExists(stageData, part.first_file))
                throw new InvalidDataException(
                    $"Final staged data is missing the sample file from {part.name}: {part.first_file}"
                );
        }

        // Promote the complete new dataset. Keep the previous version until the marker is committed.
        if (Directory.Exists(backupData))
            Directory.Delete(backupData, true);

        bool movedOldData = false;
        if (Directory.Exists(finalData))
        {
            Directory.Move(finalData, backupData);
            movedOldData = true;
        }

        try
        {
            Directory.Move(stageData, finalData);
            WriteTextAtomic(
                completionMarker,
                manifest.transfer_id + "|" + manifest.file_count
            );
        }
        catch
        {
            if (Directory.Exists(finalData))
                Directory.Delete(finalData, true);
            if (movedOldData && Directory.Exists(backupData))
                Directory.Move(backupData, finalData);
            throw;
        }

        if (Directory.Exists(backupData))
            Directory.Delete(backupData, true);
        if (Directory.Exists(stageRoot))
            Directory.Delete(stageRoot, true);

        // Archives may already have been removed part by part. This final pass handles leftovers.
    }


    private static int ExtractTarArchive(string archivePath, string stageRoot)
    {
        int fileCount = 0;
        byte[] buffer = new byte[1024 * 1024];
        string dataRoot = Path.GetFullPath(Path.Combine(stageRoot, "Data"));
        string dataRootPrefix = dataRoot.TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar)
            + Path.DirectorySeparatorChar;

        using (FileStream fileStream = new FileStream(archivePath, FileMode.Open, FileAccess.Read, FileShare.Read))
        using (TarInputStream tar = new TarInputStream(fileStream, Encoding.UTF8))
        {
            TarEntry entry;
            while ((entry = tar.GetNextEntry()) != null)
            {
                string entryName = entry.Name;
                string destination = GetSafeEntryPath(entryName, stageRoot, dataRoot, dataRootPrefix);
                byte typeFlag = entry.TarHeader.TypeFlag;

                if (entry.IsDirectory || typeFlag == TarHeader.LF_DIR)
                {
                    Directory.CreateDirectory(destination);
                    continue;
                }

                // The Python builder only adds regular files and directories. Reject links and
                // special TAR entry types rather than allowing them to escape the Data tree.
                if (typeFlag != TarHeader.LF_NORMAL && typeFlag != TarHeader.LF_OLDNORM)
                {
                    throw new InvalidDataException(
                        $"Unsupported TAR entry type '{(char)typeFlag}' in {archivePath}: {entryName}"
                    );
                }

                string directory = Path.GetDirectoryName(destination);
                if (!string.IsNullOrEmpty(directory))
                    Directory.CreateDirectory(directory);

                using (FileStream output = new FileStream(destination, FileMode.Create, FileAccess.Write, FileShare.None))
                {
                    long copied = 0;
                    int read;
                    while ((read = tar.Read(buffer, 0, buffer.Length)) > 0)
                    {
                        output.Write(buffer, 0, read);
                        copied += read;
                    }

                    if (copied != entry.Size)
                    {
                        throw new InvalidDataException(
                            $"Truncated TAR entry {entryName}: expected {entry.Size} bytes, wrote {copied}."
                        );
                    }
                }

                fileCount++;
            }
        }

        return fileCount;
    }

    private static string GetSafeEntryPath(
        string entryName,
        string stageRoot,
        string dataRoot,
        string dataRootPrefix)
    {
        if (string.IsNullOrEmpty(entryName))
            throw new InvalidDataException("TAR contains an empty entry name.");

        string normalized = entryName.Replace('\\', '/').TrimEnd('/');
        if (normalized == "Data")
            return dataRoot;

        if (normalized.StartsWith("/", StringComparison.Ordinal) ||
            !normalized.StartsWith("Data/", StringComparison.Ordinal))
        {
            throw new InvalidDataException("TAR entry is outside the expected Data/ root: " + entryName);
        }

        string relative = normalized.Substring("Data/".Length);
        string[] segments = relative.Split('/');
        foreach (string segment in segments)
        {
            if (string.IsNullOrEmpty(segment) || segment == "." || segment == ".." || segment.Contains(":"))
                throw new InvalidDataException("Unsafe TAR entry path: " + entryName);
        }

        string destination = Path.GetFullPath(
            Path.Combine(stageRoot, "Data", relative.Replace('/', Path.DirectorySeparatorChar))
        );

        if (!destination.StartsWith(dataRootPrefix, StringComparison.Ordinal) &&
            !string.Equals(destination, dataRoot, StringComparison.Ordinal))
        {
            throw new InvalidDataException("TAR entry resolves outside the Data directory: " + entryName);
        }

        return destination;
    }

    private static bool SampleFileExists(string stageData, string relativePath)
    {
        if (string.IsNullOrEmpty(relativePath))
            return true;

        string normalized = relativePath.Replace('\\', '/');
        if (normalized.StartsWith("/", StringComparison.Ordinal))
            return false;

        foreach (string segment in normalized.Split('/'))
        {
            if (string.IsNullOrEmpty(segment) || segment == "." || segment == ".." || segment.Contains(":"))
                return false;
        }

        string fullPath = Path.GetFullPath(
            Path.Combine(stageData, normalized.Replace('/', Path.DirectorySeparatorChar))
        );
        string prefix = Path.GetFullPath(stageData).TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar)
            + Path.DirectorySeparatorChar;
        return fullPath.StartsWith(prefix, StringComparison.Ordinal) && File.Exists(fullPath);
    }

    private static void WriteTextAtomic(string path, string value)
    {
        string temporary = path + ".part";
        File.WriteAllText(temporary, value, Encoding.UTF8);
        if (File.Exists(path))
            File.Delete(path);
        File.Move(temporary, path);
    }

    private static void DeleteDownloadedArchives(string obbDirectory, TransferManifest manifest)
    {
        foreach (Part part in manifest.parts)
            TryDelete(Path.Combine(obbDirectory, part.name), true);
    }

    private static void TryDelete(string path, bool logFailure)
    {
        try
        {
            if (File.Exists(path))
                File.Delete(path);
        }
        catch (Exception exception)
        {
            if (logFailure)
                Debug.LogWarning("[DataInstaller] Could not delete downloaded archive " + path + ": " + exception.Message);
        }
    }

    private void LoadMainScene()
    {
        if (string.IsNullOrEmpty(mainSceneName))
        {
            Fail("Main Scene Name is empty on DataInstaller.");
            return;
        }

        SceneManager.LoadScene(mainSceneName, LoadSceneMode.Single);
    }

    private void Fail(string message)
    {
        Debug.LogError("[DataInstaller] " + message, this);
    }
}
